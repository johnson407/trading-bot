<?php

namespace App\Domain\Grid;

use App\Domain\Grid\Enums\GridPlanProblemSeverity;
use App\Domain\Grid\ValueObjects\GridPlan;
use App\Domain\Grid\ValueObjects\GridPlanLevel;
use App\Domain\Grid\ValueObjects\GridPlanProblem;
use App\Domain\Grid\ValueObjects\GridPlanRequest;
use App\Domain\Order\Enums\OrderSide;
use App\Domain\Strategy\Exceptions\InvalidStrategyConfigurationException;
use App\Domain\Strategy\Exceptions\UnknownStrategyException;
use App\Domain\Strategy\StrategyRegistry;
use App\Domain\Strategy\ValueObjects\BotSnapshot;
use App\Domain\Strategy\ValueObjects\MarketSnapshot;
use App\Domain\Strategy\ValueObjects\StrategyConfiguration;
use App\Domain\Strategy\ValueObjects\StrategyInput;
use App\Domain\Strategy\ValueObjects\StrategyState;
use App\Domain\Support\Decimal;
use InvalidArgumentException;

/**
 * Evaluates a bot setup without touching persistence.
 *
 * Preview, creation, and update all consume this service so the ladder a user
 * sees is generated by the same strategy code that runs on the first tick.
 */
class GridPlanEvaluator
{
    /**
     * Warn when the configured center differs from the market by more than
     * this fraction (50%).
     */
    public const CENTER_PRICE_BAND = '0.5';

    public function __construct(private readonly StrategyRegistry $strategies) {}

    public function evaluate(GridPlanRequest $request): GridPlan
    {
        $configuration = new StrategyConfiguration($request->strategyKey, $request->configuration);
        $center = $this->centerPrice($configuration, $request);

        try {
            $strategy = $this->strategies->get($request->strategyKey);
            $input = new StrategyInput(
                market: MarketSnapshot::make(
                    $request->symbol,
                    $center->isPositive() ? $center : '1',
                ),
                bot: BotSnapshot::make(
                    botId: 0,
                    baseInventory: $request->baseInventory,
                    quoteInventory: $request->capitalAllocation,
                    averageEntryPrice: '0',
                    realizedPnl: '0',
                    capitalAllocation: $request->capitalAllocation,
                ),
                config: $configuration,
                state: StrategyState::empty(),
            );

            $decision = $strategy->onTick($input);
        } catch (InvalidStrategyConfigurationException|UnknownStrategyException|InvalidArgumentException $exception) {
            return $this->failedPlan($request, $configuration, $exception);
        }

        $quantities = [];

        foreach ($decision->orders as $order) {
            if ($order->gridLevelSequence !== null) {
                $quantities[$order->gridLevelSequence] = $order->quantity;
            }
        }

        $levels = [];
        $buyNotional = Decimal::zero();
        $sellNotional = Decimal::zero();
        $orderCount = 0;

        foreach ($decision->levels as $level) {
            $quantity = $quantities[$level->sequence] ?? Decimal::zero();
            $notional = $level->price->mul($quantity);

            if ($quantity->isPositive()) {
                $orderCount++;
            }

            if ($level->side === OrderSide::Buy) {
                $buyNotional = $buyNotional->add($notional);
            } else {
                $sellNotional = $sellNotional->add($notional);
            }

            $levels[] = new GridPlanLevel(
                sequence: $level->sequence,
                side: $level->side,
                price: $level->price,
                quantity: $quantity,
                notional: $notional,
            );
        }

        try {
            $orderQuantity = $configuration->has('order_quantity')
                ? Decimal::of($configuration->get('order_quantity'))
                : ($decision->orders[0]->quantity ?? Decimal::zero());
            $spacingValue = $configuration->has('spacing_value')
                ? Decimal::of($configuration->get('spacing_value'))
                : Decimal::zero();
        } catch (InvalidArgumentException $exception) {
            return $this->failedPlan($request, $configuration, $exception);
        }

        $problems = [
            ...$this->minimumProblems($request, $levels, $orderQuantity),
            ...$this->warningProblems($request, $center, $levels, $orderCount, $buyNotional, $sellNotional),
        ];

        return new GridPlan(
            strategyKey: $request->strategyKey,
            levels: $levels,
            problems: $problems,
            centerPrice: $center,
            orderQuantity: $orderQuantity,
            spacingType: (string) ($request->configuration['spacing_type'] ?? 'arithmetic'),
            spacingValue: $spacingValue,
            levelsPerSide: (int) ($request->configuration['levels_per_side'] ?? 0),
            orderCount: $orderCount,
            buyNotional: $buyNotional,
            sellNotional: $sellNotional,
        );
    }

    private function centerPrice(StrategyConfiguration $configuration, GridPlanRequest $request): Decimal
    {
        if ($configuration->has('center_price')) {
            return Decimal::of($configuration->get('center_price'));
        }

        if ($request->marketPrice !== null) {
            return Decimal::of($request->marketPrice);
        }

        return Decimal::zero();
    }

    /**
     * @param  list<GridPlanLevel>  $levels
     * @return list<GridPlanProblem>
     */
    private function minimumProblems(GridPlanRequest $request, array $levels, Decimal $orderQuantity): array
    {
        if ($request->market === null || $levels === []) {
            return [];
        }

        $problems = [];
        $minAmount = $request->market->minAmount;

        if ($minAmount->isPositive() && $orderQuantity->isPositive() && $orderQuantity->lessThan($minAmount)) {
            $problems[] = new GridPlanProblem(
                code: 'plan.minimum_amount',
                field: 'order_quantity',
                message: "Order quantity {$orderQuantity->toString()} is below the exchange minimum of "
                    ."{$minAmount->toString()} for {$request->market->symbol}.",
            );
        }

        $minNotional = $request->market->minNotional;

        if ($minNotional->isPositive()) {
            $smallest = null;

            foreach ($levels as $level) {
                if (! $level->quantity->isPositive()) {
                    continue;
                }

                if ($smallest === null || $level->notional->lessThan($smallest)) {
                    $smallest = $level->notional;
                }
            }

            if ($smallest !== null && $smallest->lessThan($minNotional)) {
                $problems[] = new GridPlanProblem(
                    code: 'plan.minimum_notional',
                    field: 'order_quantity',
                    message: "Order notional {$smallest->toString()} is below the exchange minimum of "
                        ."{$minNotional->toString()} for {$request->market->symbol}.",
                );
            }
        }

        return $problems;
    }

    /**
     * @param  list<GridPlanLevel>  $levels
     * @return list<GridPlanProblem>
     */
    private function warningProblems(
        GridPlanRequest $request,
        Decimal $center,
        array $levels,
        int $orderCount,
        Decimal $buyNotional,
        Decimal $sellNotional,
    ): array {
        $problems = [];

        if ($request->limits !== null) {
            $maxOrders = (int) ($request->limits['max_open_orders']
                ?? config('risk.defaults.max_open_orders', 20));

            if ($orderCount > $maxOrders) {
                $problems[] = new GridPlanProblem(
                    code: 'plan.max_open_orders',
                    field: 'level_count',
                    message: "This setup places {$orderCount} orders, above the current limit of {$maxOrders}. "
                        .'Reduce the level count or raise the limit on the Risk Limits page.',
                    severity: GridPlanProblemSeverity::Warning,
                );
            }

            $maxNotional = Decimal::of(
                $request->limits['max_position_notional']
                ?? config('risk.defaults.max_position_notional', '1000'),
            );

            if ($buyNotional->greaterThan($maxNotional)) {
                $problems[] = new GridPlanProblem(
                    code: 'plan.max_position_notional',
                    field: 'capital_allocation',
                    message: "Buy-side notional {$buyNotional->toString()} exceeds the current limit of "
                        ."{$maxNotional->toString()}. Reduce size or raise the limit on the Risk Limits page.",
                    severity: GridPlanProblemSeverity::Warning,
                );
            }
        }

        if ($request->marketPrice !== null && $center->isPositive()) {
            $marketPrice = Decimal::of($request->marketPrice);

            if ($marketPrice->isPositive()) {
                $difference = $center->sub($marketPrice)->abs()->div($marketPrice);

                if ($difference->greaterThan(self::CENTER_PRICE_BAND)) {
                    $percentage = $difference->mul('100')->round(2)->toString();
                    $problems[] = new GridPlanProblem(
                        code: 'plan.center_price_band',
                        field: 'center_price',
                        message: "The center price is {$percentage}% away from the latest market price of "
                            ."{$marketPrice->toString()}.",
                        severity: GridPlanProblemSeverity::Warning,
                    );
                }
            }
        }

        $hasSellLevels = $sellNotional->isPositive();

        if ($hasSellLevels && Decimal::of($request->baseInventory)->isZero()) {
            $problems[] = new GridPlanProblem(
                code: 'plan.unfunded_sells',
                field: null,
                message: 'Sell levels stay deferred until buy orders fill because the bot starts with no base inventory.',
                severity: GridPlanProblemSeverity::Warning,
            );
        }

        return $problems;
    }

    private function failedPlan(
        GridPlanRequest $request,
        StrategyConfiguration $configuration,
        InvalidArgumentException|UnknownStrategyException $exception,
    ): GridPlan {
        $reason = $exception->getMessage();

        if (str_contains($reason, ']: ')) {
            [, $reason] = explode(']: ', $reason, 2);
        }

        return new GridPlan(
            strategyKey: $request->strategyKey,
            levels: [],
            problems: [
                new GridPlanProblem(
                    code: 'plan.invalid_configuration',
                    field: $this->fieldFor($reason),
                    message: rtrim($reason, '.').'.',
                ),
            ],
            centerPrice: $this->safeCenter($request, $configuration),
            orderQuantity: Decimal::zero(),
            spacingType: (string) ($request->configuration['spacing_type'] ?? 'arithmetic'),
            spacingValue: Decimal::zero(),
            levelsPerSide: (int) ($request->configuration['levels_per_side'] ?? 0),
            orderCount: 0,
            buyNotional: Decimal::zero(),
            sellNotional: Decimal::zero(),
        );
    }

    private function safeCenter(GridPlanRequest $request, StrategyConfiguration $configuration): Decimal
    {
        try {
            return $this->centerPrice($configuration, $request);
        } catch (InvalidArgumentException) {
            return Decimal::zero();
        }
    }

    private function fieldFor(string $reason): string
    {
        return match (true) {
            str_contains($reason, 'center_price') => 'center_price',
            str_contains($reason, 'levels_per_side') => 'level_count',
            str_contains($reason, 'spacing_type') => 'spacing_type',
            str_contains($reason, 'trailing_distance') => 'trailing_distance',
            str_contains($reason, 'size_multiplier') => 'size_multiplier',
            str_contains($reason, 'max_order_quantity') => 'max_order_quantity',
            str_contains($reason, 'max_increases') => 'max_increases',
            str_contains($reason, 'max_spacing') => 'max_spacing',
            str_contains($reason, 'min_spacing') => 'min_spacing',
            str_contains($reason, 'volatility_multiplier') => 'volatility_multiplier',
            str_contains($reason, 'recalculation_interval') => 'recalculation_interval_seconds',
            str_contains($reason, 'order_quantity') => 'order_quantity',
            str_contains($reason, 'spacing'),
            str_contains($reason, 'level price'),
            str_contains($reason, 'duplicate') => 'spacing_value',
            default => 'strategy_key',
        };
    }
}
